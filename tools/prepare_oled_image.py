"""Encode an image as a row-major, MSB-first Adafruit GFX OLED bitmap."""
import argparse
from pathlib import Path

from PIL import Image, ImageOps


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("source", type=Path)
    parser.add_argument("header", type=Path)
    parser.add_argument("preview", type=Path)
    parser.add_argument("--mode", choices=("outline", "dither"), default="outline")
    parser.add_argument("--threshold", type=int, choices=range(256), default=200)
    args = parser.parse_args()

    with Image.open(args.source) as original:
        gray = ImageOps.grayscale(original)
        gray = ImageOps.contain(gray, (128, 64), Image.Resampling.LANCZOS)
        # Dark source details become illuminated pixels on the OLED.
        if args.mode == "dither":
            gray = ImageOps.autocontrast(gray, cutoff=1)
            mono = ImageOps.invert(gray).convert("1", dither=Image.Dither.FLOYDSTEINBERG)
        else:
            # Render the darker hair as solid light pixels, keeping the face dark.
            mono = gray.point(lambda value: 255 if value < args.threshold else 0, mode="1")
        canvas = Image.new("1", (128, 64), 0)
        canvas.paste(mono, ((128 - mono.width) // 2, (64 - mono.height) // 2))

    pixels = canvas.load()
    packed = bytearray()
    for y in range(64):
        for byte_x in range(16):
            value = 0
            for bit in range(8):
                if pixels[byte_x * 8 + bit, y]:
                    value |= 0x80 >> bit
            packed.append(value)
    assert len(packed) == 1024
    rows = ["  " + ", ".join("0x{:02X}".format(v) for v in packed[i:i + 16])
            for i in range(0, len(packed), 16)]
    header = (
        "// Generated by tools/prepare_oled_image.py. One bit per pixel.\n"
        "#pragma once\n#include <Arduino.h>\n\n"
        "const uint8_t oledImage[] PROGMEM = {\n"
        + ",\n".join(rows)
        + "\n};\nstatic_assert(sizeof(oledImage) == 1024, \"Invalid OLED bitmap size\");\n"
    )
    args.header.parent.mkdir(parents=True, exist_ok=True)
    args.preview.parent.mkdir(parents=True, exist_ok=True)
    args.header.write_text(header, encoding="ascii")
    canvas.save(args.preview)
    canvas.resize((512, 256), Image.Resampling.NEAREST).save(
        args.preview.with_name(args.preview.stem + "-4x.png"))
    print("OLED bitmap: 128x64, {} bytes; fitted source: {}x{}".format(
        len(packed), mono.width, mono.height))


if __name__ == "__main__":
    main()
